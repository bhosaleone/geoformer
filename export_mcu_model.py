"""
Export GeoFormer-MCU Trained Checkpoint to C Header for Arduino Uno / ATmega328P
=================================================================================
Packs:
- W_LATTICE: 32x32 4-bit conductances into Flash (PROGMEM)
- W_IN: 16x32 ternary weights into Flash (PROGMEM)
- W_OUT: 32x16 ternary weights into Flash (PROGMEM)
- Test Queries & Adversarial Test Vectors into Flash

Author: Shrikant Bhosale (Atmabhan Pandit), GMC Sambhajinagar
Zenodo DOI: 10.5281/zenodo.23730305
"""

import os
import torch

CKPT_PATH = "checkpoints/geoformer_mcu_uno32.pt"
OUTPUT_HEADER = "firmware/uno_nano_geoformer/mcu_weights.h"


def export():
    print(f"Loading checkpoint: {CKPT_PATH}")
    ckpt = torch.load(CKPT_PATH, map_location="cpu")

    num_nodes = ckpt["num_nodes"]
    d_model = ckpt["d_model"]
    w_lattice = ckpt["w_lattice"].numpy() # uint8 [32, 32]
    w_in = ckpt["w_in"].numpy()           # int8 [16, 32]
    w_out = ckpt["w_out"].numpy()         # int8 [32, 16]

    print(f"Entities: {num_nodes} | Latent Dim: {d_model}")
    print(f"w_lattice shape: {w_lattice.shape} (min={w_lattice.min()}, max={w_lattice.max()})")
    print(f"w_in shape: {w_in.shape} (unique values: {sorted(list(set(w_in.flatten())))})")
    print(f"w_out shape: {w_out.shape} (unique values: {sorted(list(set(w_out.flatten())))})")

    lines = []
    lines.append("/*")
    lines.append(" * GeoFormer-MCU Pre-Trained Weights (Trained for ATmega328P)")
    lines.append(" * Auto-generated by export_mcu_model.py")
    lines.append(" * Author: Shrikant Bhosale (Atmabhan Pandit), GMC Sambhajinagar")
    lines.append(" * Zenodo DOI: 10.5281/zenodo.23730305")
    lines.append(" */\n")
    lines.append("#ifndef MCU_WEIGHTS_H")
    lines.append("#define MCU_WEIGHTS_H\n")
    lines.append("#include <avr/pgmspace.h>\n")
    lines.append(f"#define MCU_NUM_NODES {num_nodes}")
    lines.append(f"#define MCU_D_MODEL {d_model}\n")

    # 1. Metric Conductance Lattice (32x32 = 1,024 bytes Flash)
    lines.append("// 4-bit Metric Conductance Lattice W (32x32)")
    lines.append("const uint8_t W_LATTICE[MCU_NUM_NODES][MCU_NUM_NODES] PROGMEM = {")
    for i in range(num_nodes):
        row_str = ", ".join(f"{int(w_lattice[i, j])}" for j in range(num_nodes))
        lines.append(f"    {{ {row_str} }}, // Node {i}")
    lines.append("};\n")

    # 2. Ternary Input Projection (16x32 = 512 bytes Flash)
    lines.append("// 1.58-bit Ternary Input Projection Weights W_IN (16x32, values in {-1, 0, +1})")
    lines.append("const int8_t W_IN[MCU_D_MODEL][MCU_NUM_NODES] PROGMEM = {")
    for d in range(d_model):
        row_str = ", ".join(f"{int(w_in[d, j])}" for j in range(num_nodes))
        lines.append(f"    {{ {row_str} }}, // Latent dim {d}")
    lines.append("};\n")

    # 3. Ternary Output Projection (32x16 = 512 bytes Flash)
    lines.append("// 1.58-bit Ternary Output Projection Weights W_OUT (32x16, values in {-1, 0, +1})")
    lines.append("const int8_t W_OUT[MCU_NUM_NODES][MCU_D_MODEL] PROGMEM = {")
    for n in range(num_nodes):
        row_str = ", ".join(f"{int(w_out[n, d])}" for d in range(d_model))
        lines.append(f"    {{ {row_str} }}, // Node {n}")
    lines.append("};\n")

    # 4. Clean Test Evaluation Queries
    test_2hop = ckpt["test_2hop"]
    lines.append(f"#define NUM_TEST_2HOP {len(test_2hop)}")
    lines.append("const uint8_t TEST_2HOP_SRC[NUM_TEST_2HOP] PROGMEM = { " + ", ".join(str(s) for s, _ in test_2hop) + " };")
    lines.append("const uint8_t TEST_2HOP_TGT[NUM_TEST_2HOP] PROGMEM = { " + ", ".join(str(t) for _, t in test_2hop) + " };\n")

    test_3hop = ckpt["test_3hop"]
    lines.append(f"#define NUM_TEST_3HOP {len(test_3hop)}")
    lines.append("const uint8_t TEST_3HOP_SRC[NUM_TEST_3HOP] PROGMEM = { " + ", ".join(str(s) for s, _ in test_3hop) + " };")
    lines.append("const uint8_t TEST_3HOP_TGT[NUM_TEST_3HOP] PROGMEM = { " + ", ".join(str(t) for _, t in test_3hop) + " };\n")

    # 5. Adversarial Probes
    adv = ckpt["adversarial_crossroads"]
    lines.append(f"#define NUM_ADV_PROBES {len(adv)}")
    lines.append("const uint8_t ADV_SRC[NUM_ADV_PROBES] PROGMEM = { " + ", ".join(str(s) for s, _, _ in adv) + " };")
    lines.append("const uint8_t ADV_DISALLOWED[NUM_ADV_PROBES] PROGMEM = { " + ", ".join(str(t) for _, t, _ in adv) + " };\n")

    lines.append("#endif // MCU_WEIGHTS_H\n")

    content = "\n".join(lines)
    with open(OUTPUT_HEADER, "w") as f:
        f.write(content)

    print(f"[OK] C Header Exported Successfully: {OUTPUT_HEADER}")
    total_flash = num_nodes * num_nodes + d_model * num_nodes + num_nodes * d_model
    print(f"Total Weights Flash Footprint: {total_flash:,} bytes ({total_flash / 1024:.2f} KB) out of 32 KB Flash!")


if __name__ == "__main__":
    export()
